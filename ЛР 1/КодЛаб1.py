print("=== Расчет силы гравитационного притяжения ===") 

G = float(input("Введите гравитационную постоянную G (например, 6.674e-11): "))
m1 = float(input("Введите массу первого тела m1 в кг (например, 5.97e24): "))
m2 = float(input("Введите массу второго тела m2 в кг (например, 7.34e22): "))
r = float(input("Введите расстояние r в метрах (например, 3.84e8): ")) 

F = G * (m1 * m2) / (r ** 2) 

print(f"\nРезультат расчета:")
print(f"Сила гравитационного притяжения F = {F:.4f} Н")
